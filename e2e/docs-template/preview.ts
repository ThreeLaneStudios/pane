// #470 docs-template PR: a standalone, self-contained static HTML
// rendering of the same content as page.ts's `+page.svelte`, meant to be
// opened directly from disk (file://) with zero build step -- the CI
// artifact's actual proof surface, since a `.svelte` file renders nothing
// on its own.
//
// The CSS below is a small, original approximation of the generated
// page's typography (dark background, card-style callouts, full-width
// rounded screenshots) -- it is NOT copied from paneapp-ai's
// `$lib/styles/docs.css` (that file's rules reference CSS custom
// properties -- `var(--radius-card)`, `var(--bg-border)`, etc. -- defined
// elsewhere in that app's own global stylesheet, and lifting them here
// without their definitions would either silently fall through to
// browser defaults or require vendoring more of that repo than "read for
// format reference only" allows). This preview is for confirming the
// *content* reads as a coherent docs page -- title, prerequisite, six
// numbered steps with captions and images -- not for pixel-matching the
// live site's exact visual design, which is what the real `+page.svelte`
// (rendered through the site's actual layout, in the later publish PR)
// is for.
import { escapeHtmlAttr, escapeHtmlText, renderInlineProse } from './render-prose.ts';
import type { JourneyManifest } from '../journeys/_runner.ts';

const PREVIEW_CSS = `
  :root { color-scheme: dark; }
  body {
    margin: 0;
    padding: 40px 24px 80px;
    background: #0e0e13;
    color: #e4e4ea;
    font-family: -apple-system, BlinkMacSystemFont, 'Inter', 'Segoe UI', sans-serif;
    line-height: 1.6;
  }
  .preview-note {
    max-width: 720px;
    margin: 0 auto 28px;
    padding: 10px 16px;
    background: #1c1c26;
    border: 1px solid #33333f;
    border-radius: 8px;
    font-size: 13px;
    color: #9a9aab;
  }
  article {
    max-width: 720px;
    margin: 0 auto;
  }
  h1 { font-size: 28px; margin: 0 0 6px; }
  h2 { font-size: 19px; margin: 32px 0 12px; }
  .meta { color: #9a9aab; font-size: 13px; margin-bottom: 20px; }
  .d-prereq { background: #1c1c26; border: 1px solid #33333f; border-radius: 8px; padding: 12px 16px; }
  .d-shot {
    display: block;
    width: 100%;
    height: auto;
    margin: 0 0 14px;
    border-radius: 8px;
    border: 1px solid #33333f;
  }
  .d-call { background: #16161e; border: 1px solid #262632; border-radius: 8px; padding: 14px 16px; margin: 0 0 8px; }
  .d-call p { margin: 0; }
  .d-fork { margin-top: 10px; font-size: 14px; color: #9a9aab; }
  .d-fork a { color: #5ce0d2; }
  .d-fork-pending { font-style: italic; }
  strong { color: #ffffff; }
`;

function renderForkLineHtml(fork: { journey: string; label: string }, knownJourneys: ReadonlySet<string>): string {
  if (knownJourneys.has(fork.journey)) {
    return `      <p class="d-fork">→ <a href="/docs/${escapeHtmlAttr(fork.journey)}">${escapeHtmlText(fork.label)}</a></p>`;
  }
  return `      <p class="d-fork d-fork-pending">→ ${escapeHtmlText(fork.label)} (coming soon)</p>`;
}

/**
 * Renders `manifest` into a complete, self-contained HTML document.
 * `imageDir` is the relative path (from the HTML file's own location) to
 * the directory the six screenshots were copied into -- the generator
 * CLI copies them from `manifest.steps` in array order (never
 * `fs.readdir`s the images directory, per this PR's determinism rule) and
 * passes the same relative prefix here, so the `<img>` tags below and the
 * files actually on disk always agree.
 *
 * Deterministic: pure function of its three arguments.
 */
export function renderPreviewHtml(manifest: JourneyManifest, imageDir: string, knownJourneys: ReadonlySet<string>): string {
  const title = manifest.title;

  const stepsHtml = manifest.steps
    .map((step) => {
      const heading = `${step.index}. ${step.title}`;
      const forkLine = step.fork !== undefined ? `\n${renderForkLineHtml(step.fork, knownJourneys)}` : '';
      return [
        `    <h2>${escapeHtmlText(heading)}</h2>`,
        `    <img class="d-shot" src="${imageDir}/${encodeURIComponent(step.image)}" alt="${escapeHtmlAttr(step.title)}" loading="lazy" />`,
        `    <div class="d-call">`,
        `      <p>${renderInlineProse(step.caption)}</p>${forkLine}`,
        `    </div>`,
      ].join('\n');
    })
    .join('\n\n');

  const prereqHtml =
    manifest.prerequisite !== undefined ? `  <p class="d-prereq">${renderInlineProse(manifest.prerequisite)}</p>\n` : '';

  return `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8" />
<title>${escapeHtmlText(title)} — Pane Docs (CI preview)</title>
<style>${PREVIEW_CSS}</style>
</head>
<body>
<div class="preview-note">
  CI preview, not the published page (#470). Generated by
  e2e/docs-template/ from the same run's journey manifest; the real
  deliverable is the sibling +page.svelte file in this artifact.
</div>
<article>
  <h1>${escapeHtmlText(title)}</h1>
  <div class="meta">Tutorial · ${manifest.steps.length} steps</div>
${prereqHtml}
${stepsHtml}
</article>
</body>
</html>
`;
}
