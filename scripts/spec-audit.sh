#!/bin/bash
set -e
cd "$(dirname "$0")/.."

echo "🔍 Running Spec Audit..."
echo ""

FAILURES=""
WARNINGS=""
NOT_BUILT_SECTIONS=""

# 2. Cross-reference closed issues with spec status
echo "🔗 Cross-referencing closed issues with spec status..."
if command -v gh &> /dev/null; then
  CLOSED_ISSUES=$(gh issue list --repo ThreeLaneStudios/pane --state closed --limit 100 --json number,title,body,closedAt 2>/dev/null || echo "[]")
  
  # Check if any closed issue references a section still marked NOT BUILT/PARTIAL
  STALE_REFS=$(echo "$CLOSED_ISSUES" | jq -r '.[] | select(.body != null) | select(.body | test("(Spec Section:|§)")) | "\(.number): \(.title) (closed \(.closedAt))\n\(.body)"' | while read -r line; do
    if echo "$line" | grep -qE '(Spec Section:|§)'; then
      # Extract section reference
      SECTION_REF=$(echo "$line" | grep -oE '(§[0-9]+\.[0-9]+|Spec Section: [0-9]+\.[0-9]+)')
      
      # Check if this section is still marked NOT BUILT/PARTIAL in spec
      if echo "$NOT_BUILT_SECTIONS" | grep -q "$SECTION_REF"; then
        echo "$line"
      fi
    fi
  done)
  
  if [ -n "$STALE_REFS" ]; then
    FAILURES="$FAILURES\n⚠️  Closed issues reference sections still marked NOT BUILT/PARTIAL:\n$STALE_REFS\n"
  else
    echo "✅ No closed issues reference incomplete spec sections"
  fi
else
  WARNINGS="$WARNINGS\n⚠️  gh CLI not available — skipping closed issue cross-reference\n"
fi
echo ""

# 3. Scan recent commits for SPEC_SKIP usage
echo "🔎 Checking for recent SPEC_SKIP bypasses..."
SKIP_COMMITS=$(git log --since="7 days ago" --all --pretty="%h %s" | grep -i "SPEC_SKIP\|SPEC_SKIP_APPROVED_BY" || true)

if [ -n "$SKIP_COMMITS" ]; then
  WARNINGS="$WARNINGS\n⚠️  Recent commits mention SPEC_SKIP:\n$SKIP_COMMITS\n"
else
  echo "✅ No SPEC_SKIP bypasses in last 7 days"
fi
echo ""

# 4. Flag old NEW issues
echo "🏷️  Checking for stale NEW issues..."
if command -v gh &> /dev/null; then
  OLD_NEW_ISSUES=$(gh issue list --repo ThreeLaneStudios/pane --state open --json number,title,body,createdAt 2>/dev/null | jq -r '.[] | select(.body != null) | select(.body | test("NEW — needs spec section")) | select((now - (.createdAt | fromdateiso8601)) > 604800) | "\(.number): \(.title) (created \(.createdAt | split("T")[0]))"')
  
  if [ -n "$OLD_NEW_ISSUES" ]; then
    FAILURES="$FAILURES\n⚠️  Issues with 'NEW — needs spec section' older than 7 days:\n$OLD_NEW_ISSUES\n"
  else
    echo "✅ No stale NEW issues"
  fi
else
  WARNINGS="$WARNINGS\n⚠️  gh CLI not available — skipping stale NEW issue check\n"
fi
echo ""

# 5. (removed, #445) This check used to list open issues labeled
# needs-spec-section. docs-issue-check.yml and issue-triage-ai.mjs (#445)
# stopped applying that label, so a label query here would only ever
# surface stale manual labeling, not a live signal, and a body-text
# heuristic would duplicate check #4 above without being any more honest.
# Dropped rather than replaced: an always-empty or always-everything
# result would be worse than no check at all. Matt deletes the
# needs-spec-section label itself in a follow-up once #445 merges.

# Output summary
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "Spec Audit Summary"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"

if [ -n "$WARNINGS" ]; then
  echo -e "$WARNINGS"
fi

if [ -n "$FAILURES" ]; then
  echo -e "$FAILURES"
  echo ""
  echo "❌ SPEC AUDIT FAILED"
  
  # Create GitHub issue for failures
  if command -v gh &> /dev/null; then
    ISSUE_BODY="# Spec Audit Failed — $(date +%Y-%m-%d)

## Failures
$(echo -e "$FAILURES" | sed 's/^//')

## Warnings
$(echo -e "$WARNINGS" | sed 's/^//')

---
*Generated by \`scripts/spec-audit.sh\`*"
    
    echo ""
    echo "📝 Creating GitHub issue for audit failures..."
    gh issue create \
      --repo ThreeLaneStudios/pane \
      --title "Spec Audit Failed — $(date +%Y-%m-%d)" \
      --label "audit" \
      --body "$ISSUE_BODY" 2>/dev/null || echo "⚠️  Failed to create GitHub issue"
  fi
  
  exit 1
else
  echo "✅ SPEC AUDIT PASSED"
  exit 0
fi
